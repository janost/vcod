#!/usr/bin/env python3
"""Dump CoD4 1.7's gsc builtin tables from `cod4_lnxded` (md5
bf8448740b3f4cb74c2254f01af14cdd, `CoD4 MP 1.7 build linux-i386 Jun 28 2008`).

    python3 -I tools/re/cod4_builtins.py cod4_lnxded          # summary
    python3 -I tools/re/cod4_builtins.py cod4_lnxded --rows   # every row
    python3 -I tools/re/cod4_builtins.py cod4_lnxded --rust   # crates/server/src/game/builtins/cod4_names.rs

The binary is stripped and the game is linked in, ET_EXEC with real
pointers in `.data`. A builtin row is 12 bytes {char *name; void (*fn)();
int developer}, methods included, as CoD2's. A table is a run of at least
four such rows (name an identifier, fn inside `.text`, developer 0 or 1);
each run found starts on a row code points at and ends on a null row or on
text (docs/research/cod4-gsc.md section 2). Which class a method table
serves is read off its first names; the one 12-byte run whose names are
client commands (`userinfo` .. `unmuteplayer`) is not a builtin table.
"""
import hashlib
import re
import struct
import sys

MD5 = "bf8448740b3f4cb74c2254f01af14cdd"

path = sys.argv[1]
mode = sys.argv[2] if len(sys.argv) > 2 else ""
d = open(path, "rb").read()
if hashlib.md5(d).hexdigest() != MD5:
    sys.exit(f"{path}: not cod4_lnxded 1.7 (md5 {MD5})")

shoff = struct.unpack_from("<I", d, 0x20)[0]
shentsize, shnum, shstrndx = struct.unpack_from("<HHH", d, 0x2E)
secs = []
names = {}
for i in range(shnum):
    nm, typ, _, addr, off, size = struct.unpack_from("<IIIIII", d, shoff + i * shentsize)
    if typ == 1 and addr:
        secs.append((addr, off, size, nm))
_, _, _, _, stroff, _ = struct.unpack_from("<IIIIII", d, shoff + shstrndx * shentsize)
text = None
for addr, off, size, nm in secs:
    if d[stroff + nm : d.index(b"\0", stroff + nm)] == b".text":
        text = (addr, addr + size)


def v2o(va):
    for a, o, s, _ in secs:
        if a <= va < a + s:
            return o + va - a
    return None


IDENT = re.compile(rb"[A-Za-z_][A-Za-z0-9_]{0,63}\x00")


def name_at(va):
    o = v2o(va)
    if o is None:
        return None
    m = IDENT.match(d, o)
    return m.group()[:-1].decode() if m else None


def row(va):
    o = v2o(va)
    if o is None or o + 12 > len(d):
        return None
    p, fn, dev = struct.unpack_from("<III", d, o)
    n = name_at(p)
    if n and text[0] <= fn < text[1] and dev in (0, 1):
        return (n, fn, dev)
    return None


def code_refs(va):
    """`.text` addresses whose bytes hold `va` (the walker's operand)."""
    b = struct.pack("<I", va)
    out = []
    for a, o, s, _ in secs:
        if a != text[0]:
            continue
        i = d.find(b, o, o + s)
        while i != -1:
            out.append(a + i - o)
            i = d.find(b, i + 1, o + s)
    return out


tables = []
for a, o, s, _ in secs:
    va = a
    while va + 12 <= a + s:
        if row(va) is None:
            va += 4
            continue
        run = []
        while row(va + 12 * len(run)) is not None:
            run.append(row(va + 12 * len(run)))
        if len(run) >= 4:
            tables.append((va, run))
            va += 12 * len(run)
        else:
            va += 4

# Each table by its first name: what kind of receiver the names serve.
KINDS = {
    "createprintchannel": "functions",
    "giveweapon": "player",
    "moveto": "scriptent",
    "freehelicopter": "vehicle",
    "attach": "entity",
    "settext": "hudelem",
    "userinfo": None,  # SV_ExecuteClientCommand's ucmds, not gsc
}
found = {}
for va, run in tables:
    kind = KINDS.get(run[0][0], "?")
    if kind is None:
        continue
    found[kind] = (va, run)
missing = [k for k, v in KINDS.items() if v and v not in found]
if missing or "?" in found:
    sys.exit(f"table shapes changed: missing {missing}, unknown {found.get('?')}")

ORDER = ["functions", "player", "scriptent", "vehicle", "entity", "hudelem"]

if mode == "--rows":
    for k in ORDER:
        va, run = found[k]
        for i, (n, fn, dev) in enumerate(run):
            print(k, i, n, f"0x{fn:x}", dev)
elif mode == "--rust":
    print("//! CoD4 1.7's gsc builtin tables, generated by `tools/re/cod4_builtins.py`")
    print("//! from `cod4_lnxded`; do not edit by hand (docs/research/cod4-gsc.md")
    print("//! section 2). Each row is `(name, developer)`.")
    print("")
    for i, k in enumerate(ORDER):
        if i:
            print("")
        va, run = found[k]
        refs = ", ".join(f"0x{r:x}" for r in code_refs(va))
        what = "functions" if k == "functions" else f"{k} methods"
        const = "FUNCTIONS" if k == "functions" else f"{k.upper()}_METHODS"
        print(f"/// The {what} (0x{va:x}, {len(run)} rows; walked at {refs}).")
        print("#[rustfmt::skip]")
        print(f"pub const {const}: &[(&str, bool)] = &[")
        for n, _, dev in run:
            print(f'    ("{n.lower()}", {"true" if dev else "false"}),')
        print("];")
else:
    for k in ORDER:
        va, run = found[k]
        dev = sum(r[2] for r in run)
        refs = " ".join(f"0x{r:x}" for r in code_refs(va))
        print(f"{k:10} 0x{va:x} {len(run):4} rows ({dev} developer) walked at {refs}")
