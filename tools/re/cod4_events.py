#!/usr/bin/env python3
"""Dump CoD4 1.7's entity event names from a binary: `cod4_lnxded` (ELF) or
`iw3mp.exe` (PE). The table is an array of string pointers, `EV_NONE`
first, indexed by event number: the client's `CG_EntityEvent` prints
`eventnames[event]` after `CG_EntityEvent:%s` (iw3mp.exe 0x435d88, table at
0x7294f0; cod4_lnxded's copy at 0x826ac20). It ends at the first pointer
that reads no `EV_` string.

    python3 -I tools/re/cod4_events.py iw3mp.exe          # index name rows
    python3 -I tools/re/cod4_events.py iw3mp.exe --rust   # crates/cod4/src/net/events.rs
"""
import struct
import sys

path = sys.argv[1]
rust = "--rust" in sys.argv
d = open(path, "rb").read()

secs = []  # (va, file offset, size)
if d[:4] == b"\x7fELF":
    shoff = struct.unpack_from("<I", d, 0x20)[0]
    shentsize, shnum = struct.unpack_from("<HH", d, 0x2E)
    for i in range(shnum):
        _, typ, _, addr, off, size = struct.unpack_from("<IIIIII", d, shoff + i * shentsize)
        if typ == 1 and addr:
            secs.append((addr, off, size))
else:
    pe = struct.unpack_from("<I", d, 0x3C)[0]
    nsec = struct.unpack_from("<H", d, pe + 6)[0]
    optsz = struct.unpack_from("<H", d, pe + 20)[0]
    base = struct.unpack_from("<I", d, pe + 24 + 28)[0]
    off = pe + 24 + optsz
    for i in range(nsec):
        vs, va, rs, pr = struct.unpack_from("<IIII", d, off + 8)
        secs.append((base + va, pr, min(vs, rs) if vs else rs))
        off += 40


def v2o(va):
    for a, o, s in secs:
        if a <= va < a + s:
            return o + va - a
    return None


def o2v(fo):
    for a, o, s in secs:
        if o <= fo < o + s:
            return a + fo - o
    return None


def cstr(va):
    o = v2o(va)
    if o is None:
        return None
    return d[o:d.find(b"\0", o)]


name_va = o2v(d.find(b"\0EV_NONE\0") + 1)
tables = []
i = d.find(struct.pack("<I", name_va))
while i != -1:
    names = []
    j = i
    while True:
        s = cstr(struct.unpack_from("<I", d, j)[0])
        if not s or not s.startswith(b"EV_"):
            break
        names.append(s.decode())
        j += 4
    tables.append((o2v(i), names))
    i = d.find(struct.pack("<I", name_va), i + 1)
tables = [t for t in tables if len(t[1]) > 1]
if len(tables) != 1:
    sys.exit(f"expected one event table, found {[(hex(a), len(n)) for a, n in tables]}")
va, names = tables[0]

if rust:
    print("//! CoD4 1.7's entity event names, generated by `tools/re/cod4_events.py`")
    print("//! from `iw3mp.exe`; do not edit by hand (docs/research/cod4-netfields.md,")
    print('//! "Event names"). `cod4_lnxded` holds the same table.')
    print()
    print(f"/// `eventnames[]` (iw3mp.exe {va:#x}), indexed by the wire's event number:")
    print("/// a playerstate's or entity's `events[]`, or an event entity's `eType`")
    print("/// minus `ET_EVENTS` (17).")
    print(f"pub const EVENT_NAMES: [&str; {len(names)}] = [")
    for n in names:
        print(f'    "{n}",')
    print("];")
    print()
    print("/// The name of event `id`, `None` past the table.")
    print("pub fn event_name(id: u32) -> Option<&'static str> {")
    print("    EVENT_NAMES.get(id as usize).copied()")
    print("}")
else:
    print(f"table at {va:#x}, {len(names)} names")
    for k, n in enumerate(names):
        print(k, n)
