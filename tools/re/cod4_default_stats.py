#!/usr/bin/env python3
"""Print the stats a fresh CoD4 1.7 profile holds, read out of `iw3mp.exe`.

With no `mpdata` the client zeroes its 0x2000-byte stats buffer and runs
`LiveStorage_StatsInit` (0x4fc550, called from `LiveStorage_NoStatsFound` at
0x579770), which inlines `LiveStorage_TrySetStat` as plain stores into the
buffer: `mov BYTE PTR ds:<byte stat>, imm` for stats under 2000 and
`mov DWORD PTR ds:<int stat>, reg` for the rest. Stat 299 is then set to the
`stat_version` dvar's default (registered at 0x57a0d8). This walks the
objdump of StatsInit and the five class unlocks it calls, tracking the
registers it loads with immediates, and prints every non-zero stat.

    python3 -I tools/re/cod4_default_stats.py iw3mp.exe          # index value rows
    python3 -I tools/re/cod4_default_stats.py iw3mp.exe --rust   # crates/cod4/src/net/stats.rs table

Layout (docs/research/cod4-netfields.md, "The stats block"): buffer byte 0
holds a CRC-32 of bytes 4..0x2000, byte stat i sits at 4 + i, int stat
i (2000..3497) at 4 * i - 5996.
"""
import re
import subprocess
import sys

EXE = sys.argv[1]
RUST = "--rust" in sys.argv

# iw3mp.exe 1.7: the buffer's checksum word and the stats-fetched flag right
# past the 0x2000 bytes.
BUF = 0xCC18C90
FETCHED = 0xCC1AC90
STATS_INIT = (0x4FC550, 0x4FC92E)
# The calls StatsInit makes before its own stores: the range resets and the
# five class unlocks (assault, demolitions, heavy gunner, sniper, spec ops).
CLASSES = (0x4FB1E0, 0x4FC550)
# `stat_version`'s registration passes its default in a DvarValue built on
# the stack: `mov ecx, 0xa` then `mov [eax], ecx` at 0x57a0ea.
STAT_VERSION_AT = 0x57A0EA


def disasm(lo, hi):
    out = subprocess.run(
        ["objdump", "-d", "-M", "intel", "--no-show-raw-insn",
         f"--start-address={lo:#x}", f"--stop-address={hi:#x}", EXE],
        check=True, capture_output=True, text=True).stdout
    rows = []
    for line in out.splitlines():
        m = re.match(r"\s*([0-9a-f]+):\s+(.*)", line)
        if m:
            rows.append((int(m.group(1), 16), m.group(2).strip()))
    return rows


def stat_of(addr):
    off = addr - BUF
    if 4 <= off < 4 + 2000:
        return off - 4
    if 2004 <= off < 0x2000 and (off - 2004) % 4 == 0:
        return 2000 + (off - 2004) // 4
    return None


stats = {}
regs = {}
for lo, hi in (CLASSES, STATS_INIT):
    for addr, ins in disasm(lo, hi):
        m = re.match(r"mov\s+(e[a-d]x|e[sd]i|[a-d]l),(0x[0-9a-f]+)$", ins)
        if m:
            r, v = m.group(1), int(m.group(2), 16)
            regs[r] = v
            if r in ("eax", "ebx", "ecx", "edx"):
                regs[r[1] + "l"] = v & 0xFF
            continue
        m = re.match(r"xor\s+(\w+),(\w+)$", ins)
        if m and m.group(1) == m.group(2):
            regs[m.group(1)] = 0
            if m.group(1) in ("eax", "ebx", "ecx", "edx"):
                regs[m.group(1)[1] + "l"] = 0
            continue
        # objdump drops the size on a store from eax: `mov ds:<addr>,eax`.
        m = re.match(r"mov\s+(?:BYTE PTR |DWORD PTR )?ds:(0x[0-9a-f]+),(\w+)$", ins)
        if not m:
            continue
        a = int(m.group(1), 16)
        if a == FETCHED + 1:
            continue  # statWriteNeeded
        s = stat_of(a)
        if s is None:
            continue
        src = m.group(2)
        v = int(src, 16) if src.startswith("0x") else regs.get(src)
        if v is None:
            sys.exit(f"{addr:#x}: store from untracked {src}")
        stats[s] = v

ver = [i for a, i in disasm(STAT_VERSION_AT, STAT_VERSION_AT + 5)]
m = re.match(r"mov\s+ecx,(0x[0-9a-f]+)$", ver[0])
if not m:
    sys.exit(f"stat_version default not at {STAT_VERSION_AT:#x}: {ver}")
stats[299] = int(m.group(1), 16)

rows = sorted((s, v) for s, v in stats.items() if v)
if RUST:
    print("/// A fresh 1.7 profile's non-zero stats, `(index, value)`: what")
    print("/// `LiveStorage_StatsInit` (iw3mp.exe 0x4fc550) stores, and stat 299 set")
    print("/// to `stat_version`'s default. Generated by")
    print("/// `tools/re/cod4_default_stats.py`; do not edit by hand.")
    print(f"pub const DEFAULT_STATS: [(u16, u32); {len(rows)}] = [")
    for s, v in rows:
        print(f"    ({s}, {v}),")
    print("];")
else:
    for s, v in rows:
        print(s, v)
