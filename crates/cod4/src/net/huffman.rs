/// The NYT symbol: a decode stops on it.
const END: u16 = 256;

/// A trie link at or past this is a leaf: the symbol is `link - LEAF`.
const LEAF: u16 = 0x8000;

/// The 1.7 code: [`CODES`] as bit strings for the writer and as a trie for
/// the reader.
pub struct Huffman {
    /// Per symbol: the code, step `i` in bit `i`, and its length.
    codes: [(u16, u8); 257],
    /// Interior nodes, the root first; each holds its `0` and `1` links.
    trie: Vec<[u16; 2]>,
}

impl Default for Huffman {
    fn default() -> Self {
        Self::new()
    }
}

impl Huffman {
    pub fn new() -> Huffman {
        let mut h = Huffman {
            codes: [(0, 0); 257],
            trie: vec![[0; 2]],
        };
        for (sym, code) in CODES.iter().enumerate() {
            let steps: Vec<usize> = code.bytes().map(|b| (b - b'0') as usize).collect();
            h.codes[sym] = (
                steps.iter().rev().fold(0, |acc, &b| acc << 1 | b as u16),
                steps.len() as u8,
            );
            let (last, path) = steps.split_last().expect("no empty code");
            let mut at = 0;
            for &b in path {
                if h.trie[at][b] == 0 {
                    h.trie.push([0; 2]);
                    h.trie[at][b] = (h.trie.len() - 1) as u16;
                }
                at = h.trie[at][b] as usize;
            }
            h.trie[at][*last] = LEAF + sym as u16;
        }
        h
    }

    /// Bits in a byte's code.
    pub fn code_len(&self, sym: u8) -> usize {
        self.codes[sym as usize].1 as usize
    }

    /// A byte's code as a 0/1 string, root first.
    pub fn code(&self, sym: u8) -> String {
        CODES[sym as usize].to_string()
    }

    /// `MSG_ReadBitsCompress`: decode until the input's bits run out, so the
    /// pad bits of the last byte may decode to a stray byte or two.
    pub fn decompress(&self, src: &[u8]) -> Vec<u8> {
        let bits = src
            .iter()
            .flat_map(|&byte| (0..8).map(move |i| (byte >> i & 1) as usize));
        let mut out = Vec::new();
        let mut at = 0;
        for b in bits {
            let link = self.trie[at][b];
            if link < LEAF {
                at = link as usize;
                continue;
            }
            if link - LEAF == END {
                break;
            }
            out.push((link - LEAF) as u8);
            at = 0;
        }
        out
    }

    /// `MSG_WriteBitsCompress`: each byte's code, LSB-first, zero padded.
    pub fn compress(&self, src: &[u8]) -> Vec<u8> {
        let mut out = Vec::with_capacity(src.len());
        let mut bit = 0usize;
        for &c in src {
            let (code, len) = self.codes[c as usize];
            for i in 0..len {
                if bit.is_multiple_of(8) {
                    out.push(0);
                }
                out[bit / 8] |= ((code >> i & 1) as u8) << (bit % 8);
                bit += 1;
            }
        }
        out
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn compress_round_trips_every_byte() {
        let h = Huffman::new();
        let data: Vec<u8> = (0..=255u8).chain(b"svc_EOF".iter().copied()).collect();
        let back = h.decompress(&h.compress(&data));
        assert_eq!(&back[..data.len()], &data[..]);
    }

    #[test]
    fn codes_fill_a_full_tree() {
        // Every interior link is used and no code prefixes another: the
        // trie build would have overwritten a link otherwise.
        let h = Huffman::new();
        assert_eq!(h.trie.len(), 256);
        assert!(h.trie.iter().flatten().all(|&l| l != 0));
        let leaves = h.trie.iter().flatten().filter(|&&l| l >= LEAF).count();
        assert_eq!(leaves, 257);
    }

    #[test]
    fn codes_are_a_huffman_code_for_the_weights() {
        // Any Huffman tree over `WEIGHTS` plus the zero-weight NYT costs the
        // same; ties only move codes between equal weights.
        let mut heap: std::collections::BinaryHeap<std::cmp::Reverse<u64>> = WEIGHTS
            .iter()
            .map(|&w| std::cmp::Reverse(w as u64))
            .chain([std::cmp::Reverse(0)])
            .collect();
        let mut optimal = 0;
        while heap.len() > 1 {
            let a = heap.pop().unwrap().0;
            let b = heap.pop().unwrap().0;
            optimal += a + b;
            heap.push(std::cmp::Reverse(a + b));
        }
        let cost: u64 = (0..256)
            .map(|s| WEIGHTS[s] as u64 * CODES[s].len() as u64)
            .sum();
        assert_eq!(cost, optimal);
    }
}
