//! The 0x2000-byte stats block a CoD4 1.7 client sends in its seven `stats`
//! packets before the gamestate (docs/research/cod4-netfields.md, "The
//! stats block"). Bytes 0..4 hold a CRC-32 of the rest; byte stat `i`
//! (0..2000) sits at `4 + i`, int stat `i` (2000..3498) at `4 * i - 5996`.

use super::pure::block_checksum_key32;

/// The block's size.
pub const STATS_BYTES: usize = 0x2000;
/// `stats` packets per block and the bytes each carries (the last 752).
pub const STAT_PACKETS: usize = 7;
pub const STAT_CHUNK: usize = 1240;

