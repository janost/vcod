/// Where stat `index` sits in the block and its width in bytes, `None`
/// past the last (3497).
pub fn stat_slot(index: u16) -> Option<(usize, usize)> {
    match index {
        0..2000 => Some((4 + index as usize, 1)),
        2000..3498 => Some((4 * index as usize - 5996, 4)),
        _ => None,
    }
}

/// A stats block: the raw bytes, the checksum word included.
#[derive(Clone)]
pub struct Stats(pub Box<[u8; STATS_BYTES]>);

impl Stats {
    /// A fresh profile's block ([`DEFAULT_STATS`]) with its checksum.
    pub fn fresh() -> Stats {
        let mut s = Stats(Box::new([0; STATS_BYTES]));
        for &(i, v) in &DEFAULT_STATS {
            s.set(i, v);
        }
        s.seal();
        s
    }

    pub fn get(&self, index: u16) -> Option<u32> {
        let (at, w) = stat_slot(index)?;
        let mut b = [0u8; 4];
        b[..w].copy_from_slice(&self.0[at..at + w]);
        Some(u32::from_le_bytes(b))
    }

    /// Sets a stat; a byte stat keeps the low byte, as the client refuses
    /// a byte stat of 0x100 or more.
    pub fn set(&mut self, index: u16, value: u32) {
        if let Some((at, w)) = stat_slot(index) {
            self.0[at..at + w].copy_from_slice(&value.to_le_bytes()[..w]);
        }
    }

    /// `LiveStorage_WriteChecksumToBuffer`: the CRC-32 of bytes 4.. into
    /// bytes 0..4.
    pub fn seal(&mut self) {
        let c = block_checksum_key32(&self.0[4..], 0);
        self.0[..4].copy_from_slice(&c.to_le_bytes());
    }

    /// The bytes `stats` packet `idx` carries.
    pub fn packet(&self, idx: usize) -> &[u8] {
        let start = STAT_CHUNK * idx;
        &self.0[start..STATS_BYTES.min(start + STAT_CHUNK)]
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn fresh_profile_passes_the_stat_integrity_check() {
        let s = Stats::fresh();
        // `_globallogic.gsc` kicks a client whose stat 205 + 10 * i reads 0.
        for i in 0..5 {
            assert_ne!(s.get(205 + 10 * i), Some(0));
        }
        assert_eq!(s.get(3025), Some(801));
        assert_eq!(s.0[4 + 205], 191);
        assert_eq!(
            &s.0[4 * 3025 - 5996..4 * 3025 - 5992],
            &801u32.to_le_bytes()
        );
        let sum = u32::from_le_bytes(s.0[..4].try_into().unwrap());
        assert_eq!(sum, block_checksum_key32(&s.0[4..], 0));
        let lens: Vec<usize> = (0..STAT_PACKETS).map(|i| s.packet(i).len()).collect();
        assert_eq!(lens, [1240, 1240, 1240, 1240, 1240, 1240, 752]);
        assert_eq!(stat_slot(3497), Some((7992, 4)));
        assert_eq!(stat_slot(3498), None);
    }
}
