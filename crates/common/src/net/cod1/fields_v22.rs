/// Each [`VEHICLE_FIELDS`] entry's index into [`ENTITY_FIELDS`]: a decoded
/// entity keeps the main table's order whichever table carried it.
pub static VEHICLE_FIELD_SLOTS: [u8; 60] = {
    let mut out = [0u8; 60];
    let mut i = 0;
    while i < VEHICLE_TABLE.len() {
        let mut j = 0;
        while ENTITY_TABLE[j].offset != VEHICLE_TABLE[i].offset {
            j += 1;
        }
        out[i] = j as u8;
        i += 1;
    }
    out
};

