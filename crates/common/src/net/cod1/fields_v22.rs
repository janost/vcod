//! Protocol 22 (United Offensive 1.51) netfield tables, dumped out of
//! coduo_lnxded 1.51b (md5 ab76f7d54388fc1ef0823b328f6fb4ec) with
//! `tools/re/netfields.py <bin> <va> <count>` at the addresses below; the
//! client's copies in CoDUOMP.exe 1.51 are equal entry for entry
//! (docs/research/coduo-diff.md, section 4). Array order is the wire order;
//! never sort or reorder.
//!
//!   entityState 0x080e11a0 (60), pushed at 0x8081e1a
//!   entityState for eType 12 0x080e1480 (60), pushed at 0x8081dce
//!   playerState 0x080e2260 (114), `cmp $0x72` at 0x8082876
//!   clientState 0x080e1c40 (22): equal to 1.1d's, so it shares `fields_v1`'s.
//!
//! `bits == -100` is a 16-bit angle (coduo-diff.md, section 3). Two names
//! keep their 1.1 spelling so a lookup by name reads every protocol's
//! table: `scale` is `_union.scale` and `fJumpOriginZ` is `fJumpPeak`.

